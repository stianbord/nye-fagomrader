/** Ikon som arver tekstfargen, med høyden til selve tegningen satt til `height` (som standard 0,8em, omtrent høyden på store bokstaver og stolper). */
export function AreaIcon({ area, height = "0.8em" }: { area: string; height?: string | number }) {
  const icon = icons[area];
  if (!icon) return null;
  const [x, y, w, h] = icon.viewBox;
  return (
    <svg viewBox={`${x} ${y} ${w} ${h}`} aria-hidden="true" style={{ display: "block", flex: "0 0 auto", position: "relative", top: "-0.025em", height, aspectRatio: `${w} / ${h}`, width: "auto" }} {...paintProps(icon)}>
      {icon.paths.map(({ d, evenodd }) => (
        <path key={d} d={d} fillRule={evenodd ? "evenodd" : undefined} clipRule={evenodd ? "evenodd" : undefined} />
      ))}
    </svg>
  );
}

/** Samme ikon som nøstet SVG i en tegning, plassert med høyre kant i `right` og overkant i `top`. */
export function AreaIconInSvg({ area, right, centerX, top, height, color }: { area: string; right?: number; centerX?: number; top: number; height: number; color: string }) {
  const icon = icons[area];
  if (!icon) return null;
  const [x, y, w, h] = icon.viewBox;
  const width = (height * w) / h;
  const left = centerX !== undefined ? centerX - width / 2 : (right ?? 0) - width;
  return (
    <svg x={left} y={top} width={width} height={height} viewBox={`${x} ${y} ${w} ${h}`} color={color} {...paintProps(icon)}>
      {icon.paths.map(({ d, evenodd }) => (
        <path key={d} d={d} fillRule={evenodd ? "evenodd" : undefined} clipRule={evenodd ? "evenodd" : undefined} />
      ))}
    </svg>
  );
}
